"use strict";
const assert = require("node:assert/strict");
const crypto = require("node:crypto");
const Sync = require("../state-record-sync");
const hash = value => crypto.createHash("sha256").update(value).digest("hex");
let counter = 0, time = 0;
const store = Sync.createStore({ hash, token: () => `token-${++counter}`, now: () => time });
let source = { orders: [{ code: "A", qty: 1 }, { code: "B", qty: 2 }], stockMovements: [{ legacy: 1 }, { id: "1", qty: 2 }], other: { a: 3 } };
let response = store.response(source, 1, "admin", "", 0);
let client = JSON.parse(JSON.stringify(Sync.apply({}, response)));
for (let i = 2; i < 70; i++) {
  source.orders.unshift({ code: String(i), qty: i });
  source.orders[1].qty++;
  if (i % 3 === 0) source.orders.pop();
  if (i % 4 === 0) source.orders.reverse();
  source.stockMovements.unshift({ id: String(i), qty: i });
  if (i % 5 === 0) source.stockMovements[3].qty++;
  const next = store.response(source, i, "admin", response.cursor, response.version);
  assert.equal(next.partial, true);
  client = Sync.apply(client, JSON.parse(JSON.stringify(next)));
  assert.deepEqual(client, source, `exact reconstruction round ${i}`);
  assert.equal(store.metrics().entries, 1, "obsolete cursor metadata is released");
  response = next;
}
const before = JSON.stringify(source);
const forbidden = store.response({ orders: [] }, 70, "seller", response.cursor, response.version);
assert.equal(forbidden.partial, false, "cross-user/role cursor cannot access baseline");
assert.deepEqual(forbidden.state.orders, []);
assert.equal(JSON.stringify(source), before);
time = 300001;
assert.equal(store.response(source, 71, "admin", response.cursor, response.version).partial, false, "expired cursor falls back to full state");
assert.equal(store.response(source, 72, "admin", "unknown", 71).partial, false);
source.orders = [{ code: "DUP", x: 1 }, { code: "DUP", x: 2 }];
const duplicate = store.response(source, 73, "admin", "unknown", 0);
source.orders[1].x = 3;
const duplicateDelta = store.response(source, 74, "admin", duplicate.cursor, 73);
assert.deepEqual(duplicateDelta.state.orders, source.orders, "duplicate IDs use full collection replacement");
const tiny = Sync.createStore({ hash, token: () => "tiny", maxBytes: 1 });
assert.equal(tiny.response(source, 1, "admin", "", 0).cursor, null);
assert.equal(tiny.metrics().estimatedBytes, 0);
assert.throws(() => Sync.apply({ orders: [] }, { partial: true, state: {}, records: { orders: { field: "code", order: ["missing"], upserts: [] } } }), /Incomplete/);
delete source.other;
const removed = store.response(source, 75, "admin", duplicateDelta.cursor, 74);
assert.deepEqual(removed.removed, ["other"]);
console.log("PASS record sync: 68 exact reconstructions, legacy rows, reordering, deletes, duplicate IDs, isolated cursors, expiry, bounded memory and missing-baseline rejection");

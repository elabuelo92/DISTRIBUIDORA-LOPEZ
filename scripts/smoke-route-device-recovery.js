"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const OrderEngine = require("../order-engine");
const Delivery = require("../delivery-engine");
const fixture = fs.readFileSync(require("node:path").join(__dirname, "smoke-delivery-operations-v132.js"), "utf8");
const build = vm.runInNewContext(`(${fixture.slice(fixture.indexOf("function buildState"), fixture.indexOf("const state = buildState"))})`, { OrderEngine });
const state = build(2);
const admin = { role: "admin", user: "Admin", username: "admin", skipMigration: true };
const driver = { role: "driver", user: "Reparto 1", username: "reparto1", deviceId: "OLD", skipMigration: true, gps: { lat: -31.4, lng: -64.2, accuracy: 10 } };
const route = Delivery.createPlannedRoute(state, { day: "2026-10-04", driverUser: "reparto1", zone: "Test", orderCodes: state.orders.map((o) => o.code) }, admin);
Delivery.publishRoute(state, route.id, admin);
Delivery.claimRoute(state, route.id, driver);
const before = JSON.stringify({ orders: state.orders, stops: route.stops, products: state.products });
assert.throws(() => Delivery.releaseRouteDevice(state, route.id, "OLD", driver), /Administracion/);
assert.throws(() => Delivery.releaseRouteDevice(state, route.id, "STALE", admin), /cambio/);
Delivery.releaseRouteDevice(state, route.id, "OLD", admin);
assert.equal(route.driverUser, "reparto1");
assert.equal(route.deviceId, "");
assert.throws(() => Delivery.collectAndDeliver(state, state.orders[0].code, { method: "Efectivo" }, driver), /Tomar la ruta/);
assert.throws(() => Delivery.claimRoute(state, route.id, { ...driver, username: "reparto2" }), /asignada a reparto1/);
Delivery.claimRoute(state, route.id, { ...driver, deviceId: "NEW" });
assert.throws(() => Delivery.collectAndDeliver(state, state.orders[0].code, { method: "Efectivo" }, driver), /asignada/);
assert.throws(() => Delivery.releaseRouteDevice(state, route.id, "OLD", admin), /cambio/);
assert.equal(JSON.stringify({ orders: state.orders, stops: route.stops, products: state.products }), before);
assert.equal(route.deviceId, "NEW");
console.log("PASS device recovery: admin-only, stale assignment blocked, owner preserved, old phone blocked, orders/stock unchanged.");

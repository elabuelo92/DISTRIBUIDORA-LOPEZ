"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const crypto=require("node:crypto");
const source=fs.readFileSync(path.join(__dirname,"../app.js"),"utf8");
const start=source.indexOf("function openTransferProofDialog(");
const end=source.indexOf("function setTransferProofMessage(",start);
assert.ok(start>=0&&end>start);
const nodes=new Map();
const byId=id=>{if(!nodes.has(id))nodes.set(id,{dataset:{},showModal(){this.open=true;}});return nodes.get(id);};
const transfer={id:"T1",amount:250000};
const context=vm.createContext({state:{bankReconciliation:[transfer]},crypto,byId,setTransferProofFile(){}});
vm.runInContext(source.slice(start,end),context);
context.openTransferProofDialog("T1");
assert.equal(byId("transferProofAmount").value,"250000");
assert.equal(byId("transferProofAmount").readOnly,false);
assert.equal(byId("transferProofAmount").dataset.expectedAmount,"250000");
const first=byId("transferProofAmount").dataset.requestId;
transfer.amount=100000;transfer.attachment={filename:"first.pdf"};
context.openTransferProofDialog("T1");
assert.equal(byId("transferProofAmount").readOnly,true);
assert.equal(byId("transferProofAmount").max,"100000");
assert.notEqual(byId("transferProofAmount").dataset.requestId,first);
assert.ok(byId("transferProofDialog").open);
console.log("PASS proof dialog: amount, stale guard, request ID and existing proof amount lock");

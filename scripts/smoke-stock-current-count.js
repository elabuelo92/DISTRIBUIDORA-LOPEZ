"use strict";
const assert = require("node:assert/strict");
const Engine = require("../order-engine");
const { createCountReferences } = require("../stock-count-storage");
let time = Date.now();
const refs = createCountReferences({ now: () => time });
const state = { products: [{ codigo_producto: "A", name: "A", stock_fisico: 100, stock_reservado: 10 }],
  orders: [], accounts: [{ credit: 11 }], stockMovements: [] };
const cutId = "CUT-CURRENT-TEST-001";
Engine.startPhysicalStockCut(state, { cutId }, "Admin");
state.products[0].stock_fisico = 80;
const input = { productCode: "A", cutId };
const ref = refs.prepare(state, input, "admin");
const count = { ...input, countId: "CNT-CURRENT-TEST-001", expectedQty: 80, countedQty: 75,
  referenceMode: "current", referenceId: ref.id };
assert.throws(() => refs.verify(state, count, "another-admin"), /vencida/);
const reference = refs.verify(state, count, "admin");
Engine.recordPhysicalCount(state, count, "Admin", reference);
assert.equal(state.physicalStockCounts[0].difference, -5);
assert.equal(state.products[0].stock_fisico, 80, "count does not alter stock");
state.products[0].stock_fisico += 7;
const adjustment = { productCode: "A", countId: count.countId, reason: "Conteo actual", expectedCurrentQty: 87 };
Engine.reconcilePhysicalCount(state, adjustment, "Admin");
assert.equal(state.products[0].stock_fisico, 82, "75 counted + 7 received afterwards");
assert.equal(Engine.recordPhysicalCount(state, count, "Admin").replayed, true, "retry does not require expired token");
assert.equal(Engine.reconcilePhysicalCount(state, adjustment, "Admin").replayed, true);
assert.equal(state.stockMovements.length, 1);
assert.equal(state.products[0].stock_reservado, 10);
assert.equal(state.physicalStockCuts[0].products[0].physical, 100);
assert.deepEqual(state.accounts, [{ credit: 11 }]);
assert.throws(() => refs.prepare(state, input, "admin"), /ya ajustado/);
const race = { products: [{ codigo_producto: "A", stock_fisico: 100 }], orders: [], stockMovements: [] };
Engine.startPhysicalStockCut(race, { cutId }, "Admin");
const stale = refs.prepare(race, input, "admin");
race.stockMovements.push({ id: "ABA", productCode: "A", qty: 0 });
assert.throws(() => refs.verify(race, { ...input, referenceId: stale.id }, "admin"), /movimientos/);
const fresh = refs.prepare(race, input, "admin");
time += 16 * 60 * 1000;
assert.throws(() => refs.verify(race, { ...input, referenceId: fresh.id }, "admin"), /vencida/);
assert.throws(() => Engine.recordPhysicalCount(race, { ...count, expectedQty: 100 }, "Admin"), /Comenzar/);
console.log("PASS current count: per-product reference, old cut separate, later receipts preserved, private/expired/moved reference blocked, replay once, reserves/accounts unchanged");

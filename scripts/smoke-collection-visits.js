"use strict";
const assert = require("node:assert/strict");
const Visits = require("../collection-visit-engine");
const Accounts = require("../account-engine");
let state = { clients: [{ codigo_cliente: "C1", name: "Cliente ficticio", balance: 1000 }], products: [{ codigo_producto: "P1", stock: 30 }],
  orders: [], accounts: [], commissionSettlements: [{ id: "LIQ", amount: 10 }],
  deliveryRoutes: [{ id: "R1", driverUser: "reparto1", deviceId: "D1", stops: [], cashTotal: 0, transferTotal: 0 }] };
Accounts.migrateState(state);
const initial = JSON.stringify(state);
const input = { requestId: "CREATE-TEST-0001", clientId: "C1", amount: 900, routeId: "R1" };
const admin = { role: "admin", username: "admin", user: "Test" };
const driver = { role: "driver", username: "reparto1", deviceId: "D1", user: "Reparto" };
assert.throws(() => Visits.create(state, input, driver));
const result = Visits.create(state, input, admin);
assert.equal(JSON.stringify(state), initial);
state = result.state;
assert.equal(Visits.create(state, input, admin).repeated, true);
const protectedBefore = JSON.stringify([state.products, state.orders, state.commissionSettlements]);
const payment = { requestId: "PAYMENT-TEST-0001", cashAmount: 400 };
const first = Visits.collect(state, result.visit.id, payment, driver);
assert.equal(state.clients[0].balance, 1000);
state = first.state;
assert.equal(state.clients[0].balance, 600);
assert.equal(state.deliveryRoutes[0].cashTotal, 400);
const after = JSON.stringify(state);
assert.equal(Visits.collect(state, result.visit.id, payment, driver).repeated, true);
assert.equal(JSON.stringify(state), after);
assert.throws(() => Visits.collect(state, result.visit.id, { ...payment, cashAmount: 500 }, driver));
assert.throws(() => Visits.collect(state, result.visit.id, { requestId: "OTHER-PAYMENT-0001", cashAmount: 600 }, driver));
assert.throws(() => Visits.collect(state, result.visit.id, payment, { ...driver, username: "reparto2" }));
state = Visits.collect(state, result.visit.id, { requestId: "TRANSFER-TEST-0001", transferAmount: 500,
  reference: "OP-1", attachment: { url: "/test/proof.jpg", filename: "proof.jpg" } }, driver).state;
assert.equal(state.clients[0].balance, 600, "Unvalidated transfer must not reduce debt");
assert.equal(state.bankReconciliation.length, 1);
assert.equal(JSON.stringify([state.products, state.orders, state.commissionSettlements]), protectedBefore);
assert.equal(state.collectionVisits[0].status, "Pendiente de validacion");
assert.equal(Visits.summary(state, result.visit.id).paid, 400);
assert.equal(Visits.summary(state, result.visit.id).pendingValidation, 500);
const transferId = state.collectionVisits[0].payments[1].transferId;
Accounts.rejectTransferProof(state, transferId, { reason: "Comprobante ilegible" }, admin);
assert.equal(Visits.summary(state, result.visit.id).pendingValidation, 500, "An observed proof cannot silently allow a duplicate collection");
Accounts.validateTransfer(state, transferId, { allowObserved: "Regularizado", operationNumber: "OP-1", bank: "Mercado Pago" }, admin);
assert.equal(Visits.summary(state, result.visit.id).status, "Cobrada");
assert.equal(state.clients[0].balance, 100);
const entries = state.accounts.length;
Accounts.validateTransfer(state, transferId, { operationNumber: "OP-1", bank: "Mercado Pago" }, admin);
assert.equal(state.accounts.length, entries);
assert.equal(state.clients[0].balance, 100);
assert.equal(JSON.stringify([state.products, state.orders, state.commissionSettlements]), protectedBefore);
state.deliveryRoutes[0].closure = { immutable: true };
assert.equal(Visits.collect(state, result.visit.id, payment, driver).repeated, true);
assert.throws(() => Visits.collect(state, result.visit.id, { requestId: "AFTER-CLOSE-001", cashAmount: 1 }, driver));
delete state.deliveryRoutes[0].closure;
state = Visits.create(state, { requestId: "SECOND-VISIT-001", clientId: "C1", amount: 100 }, admin).state;
const second = state.collectionVisits[1].id;
assert.throws(() => Visits.create(state, { requestId: "THIRD-VISIT-0001", clientId: "C1", amount: 1 }, admin));
state = Visits.assign(state, second, { routeId: "R1" }, admin).state;
state.clients[0].latitud = -31.5;
state.clients[0].longitud = -64.2;
assert.equal(Visits.summary(state, second).gps.lat, -31.5, "Uses corrected customer coordinates");
assert.throws(() => Visits.notCollected(state, second, { reason: "Cerrado" }, { ...driver, deviceId: "OTHER" }));
const noCollection = Visits.notCollected(state, second, { reason: "Local cerrado" }, driver);
state = noCollection.state;
assert.equal(Visits.summary(state, second).status, "No cobrada");
assert.equal(state.clients[0].balance, 100);
assert.throws(() => Visits.collect(state, second, { requestId: "NO-COLLECTED-001", cashAmount: 100 }, driver));
for (const amount of [null, "100", true, -1, NaN, Infinity]) {
  assert.throws(() => Visits.create(state, { requestId: "INVALID-MONEY-01", clientId: "C1", amount }, admin));
}
const beforeError = JSON.stringify(state);
assert.throws(() => Visits.assign(state, second, { routeId: "MISSING" }, admin));
assert.equal(JSON.stringify(state), beforeError);
const Delivery = require("../delivery-engine");
assert.equal(Delivery.routeClosureSummary(state.deliveryRoutes[0], { reportedCash: 400, reportedTransfer: 500 }).expectedCash, 400);
assert.equal(state.orders.length, 0);
assert.equal(state.deliveryRoutes[0].stops.length, 0, "Does not fake a sale stop");
console.log("PASS P8 core: partial cash, transfer validation/replay, route ownership/closure, no-collection, assignment, current GPS, numeric input, no stock/sales/commission changes. API/UI integration pending.");
